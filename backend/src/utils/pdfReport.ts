import PDFDocument from "pdfkit";
import type { Response } from "express";
import pool from "../config/db";

type ReportPeriod = "monthly" | "yearly";

interface ActivityRow {
  category: string;
  name: string;
  visitorCount: number;
}

export async function generatePdfReport(
  res: Response,
  period: ReportPeriod,
  year: number,
  month?: number
): Promise<void> {
  const startDate =
    period === "monthly"
      ? `${year}-${String(month).padStart(2, "0")}-01`
      : `${year}-01-01`;

  const endDate =
    period === "monthly"
      ? new Date(Date.UTC(year, month!, 1))
          .toISOString()
          .slice(0, 10)
      : `${year + 1}-01-01`;

  const totals = await pool.query(
    `SELECT
       COUNT(*)::int AS "totalRegistrations",
       COALESCE(SUM(visitor_count), 0)::int AS "totalVisitors"
     FROM visitor_registrations
     WHERE registered_at >= ($1::date AT TIME ZONE 'Africa/Johannesburg')
       AND registered_at < ($2::date AT TIME ZONE 'Africa/Johannesburg')`,
    [startDate, endDate]
  );

  const activityResult = await pool.query(
    `SELECT
       a.category,
       a.name,
       COALESCE(SUM(ra.activity_visitor_count), 0)::int AS "visitorCount"
     FROM activities a
     LEFT JOIN registration_activities ra
       ON ra.activity_id = a.id
     LEFT JOIN visitor_registrations vr
       ON vr.id = ra.registration_id
       AND vr.registered_at >= ($1::date AT TIME ZONE 'Africa/Johannesburg')
       AND vr.registered_at < ($2::date AT TIME ZONE 'Africa/Johannesburg')
     GROUP BY a.id, a.category, a.name
     ORDER BY a.id`,
    [startDate, endDate]
  );

  const activities = activityResult.rows as ActivityRow[];

  const label =
    period === "monthly"
      ? new Date(Date.UTC(year, month! - 1, 1))
          .toLocaleString("en-ZA", {
            month: "long",
            year: "numeric",
            timeZone: "UTC"
          })
      : String(year);

  const filename =
    period === "monthly"
      ? `adelaide-tambo-report-${year}-${String(month).padStart(2, "0")}.pdf`
      : `adelaide-tambo-report-${year}.pdf`;

  const doc = new PDFDocument({
    size: "A4",
    margin: 50
  });

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader(
    "Content-Disposition",
    `attachment; filename="${filename}"`
  );

  doc.pipe(res);

  doc.fontSize(20).font("Helvetica-Bold")
    .text("ADELAIDE TAMBO PUBLIC LIBRARY", { align: "center" });

  doc.moveDown(0.4);

  doc.fontSize(13).font("Helvetica")
    .text("Digital Visitor Registration Report", { align: "center" });

  doc.moveDown(0.5);

  doc.fontSize(11)
    .text(`Reporting period: ${label}`, { align: "center" });

  doc.moveDown(2);

  doc.fontSize(14).font("Helvetica-Bold")
    .text("Visitor Summary");

  doc.moveDown(0.7);

  doc.fontSize(11).font("Helvetica")
    .text(`Total registrations: ${totals.rows[0].totalRegistrations}`)
    .text(`Total visitors: ${totals.rows[0].totalVisitors}`);

  doc.moveDown(2);

  doc.fontSize(14).font("Helvetica-Bold")
    .text("Library Activity Breakdown");

  doc.moveDown(0.8);

  let currentCategory = "";

  for (const activity of activities) {
    if (activity.category !== currentCategory) {
      currentCategory = activity.category;

      doc.moveDown(0.6);
      doc.fontSize(11).font("Helvetica-Bold")
        .text(currentCategory);
    }

    doc.fontSize(10).font("Helvetica")
      .text(`${activity.name}: ${activity.visitorCount}`);
  }

  doc.moveDown(2);

  doc.fontSize(9).fillColor("gray")
    .text(
      "Generated by Adelaide Tambo Digital Visitor Registration System",
      { align: "center" }
    );

  doc.end();
}
